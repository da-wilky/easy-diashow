import { expect, test, type Page } from '@playwright/test'
import { ensureFixtures } from './fixtures'
import { createProject, drag, imageItems, imageOrder, trackItems } from './ui'

const stored = (page: Page) =>
  page.evaluate(async () => {
    const root = await navigator.storage.getDirectory()
    const entries: string[] = []
    for await (const name of root.keys()) entries.push(name)
    return { databases: (await indexedDB.databases()).map((d) => d.name), entries }
  })

test('projects persist, can be reordered, renamed, deleted and wiped', async ({ page }) => {
  const { images, tracks } = ensureFixtures()
  await page.goto('/')
  await expect(page.getByText('Noch keine Projekte.')).toBeVisible()

  await createProject(page, 'Urlaub')
  await page.getByLabel('Bilder hinzufügen').setInputFiles([images[9]!, images[1]!, images[0]!])
  await page.getByLabel('Musik hinzufügen').setInputFiles(tracks.slice(0, 1))
  const track = page.getByRole('listitem', { name: 'click120.mp3' })
  await expect(track.getByTestId('bpm')).toHaveText('120')
  expect(await imageOrder(page)).toEqual(['img1.png', 'img2.png', 'img10.png'])

  await drag(page, imageItems(page).first(), imageItems(page).last())
  expect(await imageOrder(page)).toEqual(['img2.png', 'img10.png', 'img1.png'])
  await imageItems(page).first().focus()
  await page.keyboard.press('ArrowRight')
  expect(await imageOrder(page)).toEqual(['img10.png', 'img2.png', 'img1.png'])
  await page.keyboard.press('ArrowLeft')
  expect(await imageOrder(page)).toEqual(['img2.png', 'img10.png', 'img1.png'])

  await page.getByLabel('Übergänge auf den Beat legen').check()
  await track.getByText('Tempo korrigieren').click()
  await track.getByRole('button', { name: 'BPM verdoppeln' }).click()
  await expect(track.getByTestId('bpm')).toHaveText('240')
  await expect(page.getByText('Alle Änderungen gespeichert')).toBeVisible()

  await page.reload()
  await expect(page.getByText('3 Bilder · 1 Musikstück')).toBeVisible()
  await expect(page.locator('.cover img')).toHaveCount(3)
  await page.getByRole('button', { name: 'Urlaub öffnen' }).click()
  await expect(page.getByRole('listitem', { name: 'click120.mp3' }).getByTestId('bpm')).toHaveText('240')
  await expect(page.getByLabel('Übergänge auf den Beat legen')).toBeChecked()
  expect(await imageOrder(page)).toEqual(['img2.png', 'img10.png', 'img1.png'])
  const thumbnail = imageItems(page).first().locator('img')
  await expect(thumbnail).toHaveJSProperty('complete', true)
  expect(await thumbnail.evaluate((i: HTMLImageElement) => i.naturalWidth)).toBe(640)

  await page.getByRole('button', { name: 'Nach Name sortieren' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Abbrechen' }).click()
  expect(await imageOrder(page)).toEqual(['img2.png', 'img10.png', 'img1.png'])
  await page.getByRole('button', { name: 'Nach Name sortieren' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Sortieren' }).click()
  await expect.poll(() => imageOrder(page)).toEqual(['img1.png', 'img2.png', 'img10.png'])
  await page.getByRole('button', { name: 'img2.png entfernen' }).click()
  expect(await imageOrder(page)).toEqual(['img1.png', 'img10.png'])
  await expect(page.getByText('Alle Änderungen gespeichert')).toBeVisible()

  await page.getByRole('button', { name: 'Zur Projektliste' }).click()
  await expect(page.getByText('2 Bilder · 1 Musikstück')).toBeVisible()
  await createProject(page, 'Zweites')
  await page.getByRole('button', { name: 'Zur Projektliste' }).click()
  await page.getByRole('button', { name: 'Urlaub umbenennen' }).click()
  await page.getByLabel('Neuer Name').fill('Umbenannt')
  await page.getByLabel('Neuer Name').press('Enter')
  await expect(page.getByRole('button', { name: 'Umbenannt öffnen' })).toBeVisible()
  expect((await stored(page)).entries).toHaveLength(2)

  await page.getByRole('button', { name: 'Zweites löschen' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Abbrechen' }).click()
  await expect(page.getByRole('button', { name: 'Zweites öffnen' })).toBeVisible()
  await page.getByRole('button', { name: 'Zweites löschen' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Löschen', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Zweites öffnen' })).toHaveCount(0)
  expect((await stored(page)).entries).toHaveLength(1)

  await page.getByRole('button', { name: 'Alle Daten löschen' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Alles löschen' }).click()
  await expect(page.getByText('Noch keine Projekte.')).toBeVisible()
  expect(await stored(page)).toEqual({ databases: [], entries: [] })
})

test('songs are reordered by dragging and beat settings show durations per track', async ({ page }) => {
  const { images, tracks } = ensureFixtures()
  await page.goto('/')
  await createProject(page, 'Beats')
  await expect(page.getByLabel('Übergänge auf den Beat legen')).toBeDisabled()
  await page.getByLabel('Bilder hinzufügen').setInputFiles(images)
  await page.getByLabel('Musik hinzufügen').setInputFiles(tracks)
  const fast = page.getByRole('listitem', { name: 'click120.mp3' })
  const slow = page.getByRole('listitem', { name: 'click90.mp3' })
  await expect(slow.getByTestId('bpm')).toHaveText('90')
  await expect(page.getByTestId('video-duration')).toHaveText('0:40 min')

  const trackOrder = () => trackItems(page).evaluateAll((items) => items.map((i) => i.getAttribute('aria-label')))
  expect(await trackOrder()).toEqual(['click120.mp3', 'click90.mp3'])
  await drag(page, trackItems(page).first(), trackItems(page).last(), { x: 120, y: 30 })
  expect(await trackOrder()).toEqual(['click90.mp3', 'click120.mp3'])
  await trackItems(page).first().focus()
  await page.keyboard.press('ArrowDown')
  expect(await trackOrder()).toEqual(['click120.mp3', 'click90.mp3'])

  await page.getByLabel('Übergänge auf den Beat legen').check()
  await expect(fast.getByText('= 2,0 s pro Bild')).toBeVisible()
  await expect(slow.getByText('= 2,67 s pro Bild')).toBeVisible()
  await fast.getByLabel('Beats pro Bild').fill('8')
  await fast.getByLabel('Beats pro Bild').press('Enter')
  await expect(fast.getByText('= 4,0 s pro Bild')).toBeVisible()

  await page.getByRole('radio', { name: 'Wunschzeit' }).check()
  await expect(fast.getByRole('radio', { name: '4 2,0 s' })).toBeChecked()
  await expect(slow.getByRole('radio', { name: '4 2,67 s' })).toBeChecked()
  await slow.getByRole('radio', { name: '8 5,33 s' }).check()
  const input = page.getByLabel('Wunschzeit pro Bild', { exact: true })
  await input.fill('4.2')
  await input.press('Enter')
  await expect(fast.getByRole('radio', { name: '8 4,0 s' })).toBeChecked()
  await expect(slow.getByRole('radio', { name: '8 5,33 s' })).toBeChecked()

  await fast.getByText('Tempo korrigieren').click()
  await fast.getByLabel('BPM von Hand').fill('60')
  await fast.getByLabel('BPM von Hand').press('Enter')
  await expect(fast.getByTestId('bpm')).toHaveText('60')
  await expect(fast.getByRole('radio', { name: '4 4,0 s' })).toBeChecked()
  await fast.getByRole('button', { name: 'click120.mp3 entfernen' }).click()
  await slow.getByRole('button', { name: 'click90.mp3 entfernen' }).click()
  await expect(page.getByLabel('Übergänge auf den Beat legen')).not.toBeChecked()
  await expect(page.getByLabel('Übergänge auf den Beat legen')).toBeDisabled()
})

test('several images or songs are moved and removed together', async ({ page }) => {
  const { images, tracks } = ensureFixtures()
  const names = (...numbers: number[]) => numbers.map((n) => `img${n}.png`)
  const confirm = (label: string) => page.getByRole('dialog').getByRole('button', { name: label, exact: true }).click()
  await page.goto('/')
  await createProject(page, 'Auswahl')
  await page.getByLabel('Bilder hinzufügen').setInputFiles(images.slice(0, 6))
  await page.getByLabel('Musik hinzufügen').setInputFiles(tracks)
  await expect(page.getByRole('listitem', { name: 'click90.mp3' })).toBeVisible()
  await expect.poll(() => imageOrder(page)).toEqual(names(1, 2, 3, 4, 5, 6))

  const selectMode = (section: string) => page.locator(`[data-section="${section}"]`).getByRole('button', { name: 'Auswählen', exact: true })
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await selectMode('images').click()
  await page.getByRole('checkbox', { name: 'img2.png auswählen' }).click()
  await page.getByRole('checkbox', { name: 'img4.png auswählen' }).click({ modifiers: ['Shift'] })
  await expect(page.getByText('3 ausgewählt')).toBeVisible()
  await page.getByRole('button', { name: 'Ans Ende' }).click()
  await expect.poll(() => imageOrder(page)).toEqual(names(1, 5, 6, 2, 3, 4))
  await page.getByRole('button', { name: 'An den Anfang' }).click()
  await expect.poll(() => imageOrder(page)).toEqual(names(2, 3, 4, 1, 5, 6))

  await page.getByRole('button', { name: 'Fertig' }).click()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await selectMode('images').click()
  await page.getByRole('checkbox', { name: 'img2.png auswählen' }).click()
  await page.getByRole('listitem', { name: /img1\.png/ }).click({ position: { x: 60, y: 45 } })
  await expect(page.getByText('2 ausgewählt')).toBeVisible()
  await drag(page, page.getByRole('listitem', { name: /img1\.png/ }), imageItems(page).last(), { x: 60, y: 60 })
  await expect.poll(() => imageOrder(page)).toEqual(names(3, 4, 5, 6, 2, 1))
  await page.getByRole('listitem', { name: /img2\.png/ }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => imageOrder(page)).toEqual(names(3, 4, 5, 2, 1, 6))

  await page.getByRole('button', { name: 'Auswahl entfernen' }).click()
  await confirm('Entfernen')
  await expect.poll(() => imageOrder(page)).toEqual(names(3, 4, 5, 6))
  await expect(page.getByRole('toolbar', { name: 'Auswahl' })).toHaveCount(0)

  await selectMode('music').click()
  await page.getByRole('checkbox', { name: 'click120.mp3 auswählen' }).click()
  await page.getByRole('button', { name: 'Auswahl entfernen' }).click()
  await confirm('Entfernen')
  await expect(trackItems(page)).toHaveCount(1)
  await page.getByRole('button', { name: 'Alle Musikstücke entfernen' }).click()
  await confirm('Alle entfernen')
  await expect(page.getByText('Optional: MP3-Dateien')).toBeVisible()

  await page.getByRole('button', { name: 'Alle Bilder entfernen' }).click()
  await confirm('Alle entfernen')
  await expect(page.getByText('Zieh deine Fotos hierher')).toBeVisible()
  await expect(page.getByText('Alle Änderungen gespeichert')).toBeVisible()
  const storedFiles = () =>
    page.evaluate(async () => {
    const root = await navigator.storage.getDirectory()
    const files: string[] = []
    for await (const dir of root.values()) for await (const name of (dir as FileSystemDirectoryHandle).keys()) files.push(name)
    return files
    })
  await expect.poll(storedFiles).toEqual([])
})

test('privacy notice is reachable and nothing is requested from other hosts', async ({ page }) => {
  const foreign: string[] = []
  page.on('request', (r) => {
    if (!/^(http:\/\/localhost:4173|blob:|data:)/.test(r.url())) foreign.push(r.url())
  })
  const response = await page.goto('/')
  expect(response!.headers()['content-security-policy']).toContain("default-src 'none'")
  await page.getByRole('link', { name: 'Datenschutz' }).click()
  await expect(page.getByRole('heading', { name: 'Datenschutzhinweis' })).toBeVisible()
  await page.getByRole('link', { name: 'Zurück zur Anwendung' }).click()
  await expect(page.getByRole('heading', { name: 'Projekte' })).toBeVisible()
  expect((await page.request.get('/favicon.svg')).headers()['content-type']).toContain('image/svg')
  expect(foreign).toEqual([])
  expect(await page.context().cookies()).toEqual([])
})

test('the privacy page does not reset the open project', async ({ page }) => {
  const { images } = ensureFixtures()
  await page.goto('/')
  await createProject(page, 'Hinweis')
  await page.getByLabel('Bilder hinzufügen').setInputFiles(images.slice(0, 2))
  await expect(imageItems(page)).toHaveCount(2)
  await page.getByRole('link', { name: 'Datenschutz' }).click()
  await expect(page.getByRole('heading', { name: 'Datenschutzhinweis' })).toBeVisible()
  await expect(imageItems(page).first()).toBeHidden()
  await page.getByRole('link', { name: 'Zurück zur Anwendung' }).click()
  await expect(imageItems(page)).toHaveCount(2)
  await page.getByRole('button', { name: 'img1.png entfernen' }).click()
  await expect(page.getByText('Alle Änderungen gespeichert')).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 Bild · 0 Musikstücke')).toBeVisible()
})
